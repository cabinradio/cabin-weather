def test_build_collects_top_five_per_element():
    doc = fetch_ltce.build("VSNT24V", [TEMP_OCT19], [PRECIP_OCT19], [SNOW_OCT19])
    day = doc["days"]["10-19"]
    assert day["high"][0] == [8.3, 1952] and len(day["high"]) == 5
    assert day["low"][0] == [-20.6, 1959]
    assert day["warm_low"] == [[3.3, 2023], [2.6, 1980], [2.5, 2022], [2.2, 1953]]   # empty rank skipped
    assert day["cold_high"][0] == [-9.7, 2004]
    assert day["precip"][0] == [12.7, 1964]
    assert day["snow"] == [[8.1, 1964]]
    assert doc["wxo_city_code"] == "NT-24" and doc["record_begin"] == "1942-07-01"


def test_build_without_snowfall_has_no_snow_key():
    doc = fetch_ltce.build("VSNT17V", [TEMP_OCT19], [PRECIP_OCT19], None)
    assert "snow" not in doc["days"]["10-19"]
